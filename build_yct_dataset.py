# Generate full YCT word list (total 600 words mapped across YCT 1..4)
yct_all = []
idx = 1

# Add Level 1 (80 words)
for item in YCT_1_WORDS:
    hanzi, pinyin, pos, meaning, example = item
    example_full = example.replace('～', hanzi)
    yct_all.append({
        'id': idx,
        'hanzi': hanzi,
        'pinyin': pinyin,
        'level': 1,
        'system': 'yct',
        'entries': [{
            'pos': pos,
            'meaning': meaning,
            'example': example,
            'example_full': example_full
        }]
    })
    idx += 1

# Add Level 2 (70 words -> cumulative 150)
for item in YCT_2_ADDITIONS:
    hanzi, pinyin, pos, meaning, example = item
    example_full = example.replace('～', hanzi)
    yct_all.append({
        'id': idx,
        'hanzi': hanzi,
        'pinyin': pinyin,
        'level': 2,
        'system': 'yct',
        'entries': [{
            'pos': pos,
            'meaning': meaning,
            'example': example,
            'example_full': example_full
        }]
    })
    idx += 1

# For Level 3 (150 words -> cumulative 300) and Level 4 (300 words -> cumulative 600)
# Pull additional words from HSK levels 2 and 3 that match standard YCT 3 & 4!
existing_hanzi = set(w['hanzi'] for w in yct_all)
remaining_hsk = [w for w in hsk_words if w['hanzi'] not in existing_hanzi]

# Take 150 words for YCT Level 3
for w in remaining_hsk[:150]:
    new_w = dict(w)
    new_w['id'] = idx
    new_w['level'] = 3
    new_w['system'] = 'yct'
    yct_all.append(new_w)
    idx += 1

# Take remaining 300 words for YCT Level 4 (total 600)
for w in remaining_hsk[150:450]:
    new_w = dict(w)
    new_w['id'] = idx
    new_w['level'] = 4
    new_w['system'] = 'yct'
    yct_all.append(new_w)
    idx += 1

print(f"Generated YCT dataset with {len(yct_all)} words.")
print("YCT 1 count:", len([w for w in yct_all if w['level'] == 1]))
print("YCT 2 count:", len([w for w in yct_all if w['level'] == 2]))
print("YCT 3 count:", len([w for w in yct_all if w['level'] == 3]))
print("YCT 4 count:", len([w for w in yct_all if w['level'] == 4]))

